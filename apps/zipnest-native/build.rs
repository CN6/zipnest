//! Windows resource embedding: gives zipnest.exe its icon, version metadata,
//! and a real window title. Without this, Explorer/taskbar/shortcuts would
//! fall back to a generic (blank) icon, and the exe would report an empty
//! FileVersion/ProductVersion in its VersionInfo.

use std::env;
use std::fs;
use std::path::Path;

/// Icon (and any other hand-written resources). Contains no VERSIONINFO.
const APP_RC: &str = "src/assets/app.rc";

fn main() {
    #[cfg(windows)]
    {
        // Keep the hand-written resources (the icon) working exactly as before.
        embed_resource::compile(APP_RC, embed_resource::NONE);

        println!("cargo:rerun-if-changed={APP_RC}");
        println!("cargo:rerun-if-env-changed=CARGO_PKG_VERSION");

        if let Some(out_dir) = env::var_os("OUT_DIR") {
            let rc = version_rc_path(Path::new(&out_dir));
            if fs::write(&rc, version_rc(&read_current_version())).is_ok() {
                // Compile it as its own .rc: its file stem becomes the output
                // name, so this never overwrites the icon resource.
                embed_resource::compile(&rc, embed_resource::NONE);
            }
        }
    }
}

/// `$OUT_DIR/zipnest_version.rc` — used only as the resource-compiler input, so
/// the stem stays distinct from `app` and the two link args cannot collide.
#[cfg(windows)]
fn version_rc_path(out_dir: &Path) -> std::path::PathBuf {
    out_dir.join("zipnest_version.rc")
}

/// The generated VERSIONINFO resource. `0.3.6` becomes both the numeric
/// `(0,3,6,0)` tuple and the `"0.3.6"` strings.
#[cfg(windows)]
fn version_rc(version: &str) -> String {
    let numbers = version_numbers(version);
    format!(
        r#"// Generated by build.rs from CURRENT_VERSION in src/main.rs -- do not edit.
1 VERSIONINFO
FILEVERSION {a},{b},{c},{d}
PRODUCTVERSION {a},{b},{c},{d}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "ZipNest contributors"
      VALUE "FileDescription", "ZipNest archive manager"
      VALUE "FileVersion", "{v}"
      VALUE "InternalName", "zipnest"
      VALUE "LegalCopyright", "MIT License"
      VALUE "OriginalFilename", "zipnest.exe"
      VALUE "ProductName", "ZipNest"
      VALUE "ProductVersion", "{v}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x0409, 0x04b0
  END
END
"#,
        a = numbers[0],
        b = numbers[1],
        c = numbers[2],
        d = numbers[3],
        v = version,
    )
}

/// `version` split into the four numbers VERSIONINFO wants, zero-filled.
/// Anything unparsable degrades to `0.0.0.0` instead of failing the build.
#[cfg(windows)]
fn version_numbers(version: &str) -> [u32; 4] {
    let mut numbers = [0u32; 4];
    for (slot, part) in numbers.iter_mut().zip(version.split('.')) {
        *slot = part.trim().parse().unwrap_or(0);
    }
    numbers
}

/// The version Cargo hands this crate from `[workspace.package].version`.
///
/// It used to be scraped out of `src/main.rs` with a string search for
/// `CURRENT_VERSION = "x.y.z"`. That was correct until v0.4.11 replaced the
/// literal with `env!("CARGO_PKG_VERSION")` — after which the search found
/// nothing, every build from then on embedded `0.0.0`, and Explorer's Details
/// tab and Windows' Apps list showed no version at all. Cargo already exports
/// the value to the build script, so read it.
#[cfg(windows)]
fn read_current_version() -> String {
    env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".to_string())
}

#[cfg(all(test, windows))]
mod tests {
    use super::{read_current_version, version_numbers, version_rc};

    #[test]
    fn the_embedded_version_is_the_crate_version() {
        // The guard for the v0.4.11..v0.4.27 bug: the version resource was
        // scraped out of main.rs, the literal there became
        // `env!("CARGO_PKG_VERSION")`, and every exe after that shipped with
        // 0.0.0 in its VersionInfo.
        let v = read_current_version();
        assert_ne!(v, "0.0.0", "build.rs could not read CARGO_PKG_VERSION");
        assert_eq!(v, env!("CARGO_PKG_VERSION"));
        assert!(version_numbers(&v)[0] > 0, "version {v} does not start at 1+");
    }

    #[test]
    fn numbers_and_strings_agree() {
        assert_eq!(version_numbers("0.3.6"), [0, 3, 6, 0]);
        // Degrades instead of failing the build.
        assert_eq!(version_numbers("0.0.0"), [0, 0, 0, 0]);
        let rc = version_rc("0.3.6");
        assert!(rc.contains("FILEVERSION 0,3,6,0"));
        assert!(rc.contains("PRODUCTVERSION 0,3,6,0"));
        assert!(rc.contains("VALUE \"FileVersion\", \"0.3.6\""));
        assert!(rc.contains("VALUE \"Translation\", 0x0409, 0x04b0"));
    }
}
